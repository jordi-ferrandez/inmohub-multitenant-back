export type ReminderRecurrenceType =
  | "once"
  | "daily"
  | "weekly"
  | "monthly"
  | "custom";

export type ReminderStatus = "active" | "paused" | "cancelled" | "archived";

export type ReminderOccurrenceStatus =
  | "pending"
  | "completed"
  | "skipped"
  | "cancelled";

export interface ReminderUserSummary {
  id: number;
  firstName: string;
  lastName: string;
  email: string | null;
}

export interface ReminderPropertyPerson {
  id: number;
  role: "owner" | "tenant";
  person: {
    id: number;
    firstName: string;
    lastName: string;
    email: string | null;
    phones?: Array<{
      id: number;
      phone: string;
      type: string | null;
    }> | null;
  };
}

export interface ReminderPropertySummary {
  id: number;
  number: string;
  floor: number;
  buildingId: number;
  building?: {
    id: number;
    street: string;
    number: number;
  } | null;
  propertyPersons?: ReminderPropertyPerson[];
}

export interface ReminderPersonSummary {
  id: number;
  firstName: string;
  lastName: string;
  email: string;
  phones?: Array<{
    id: number;
    phone: string;
    type: string | null;
  }> | null;
}

export interface ReminderFollowUpSummary {
  id: number;
  propertyId: number;
  plannedDate: Date | null;
  executedDate: Date | null;
  wasContacted: boolean;
  comment: string | null;
}

export interface ReminderRecurrenceConfig {
  type: ReminderRecurrenceType;
  interval?: number;
  daysOfWeek?: number[]; // 0 (domingo) - 6 (sábado)
  dayOfMonth?: number;
  customRule?: string;
  endDate?: string;
}

export interface CreateReminderRequest {
  title: string;
  note?: string;
  responsibleId: number;
  propertyId?: number;
  buildingId?: number;
  personId?: number;
  followUpId?: number;
  scheduledAt: string;
  timezone?: string;
  recurrence: ReminderRecurrenceConfig;
  metadata?: Record<string, unknown>;
}

export interface UpdateReminderRequest {
  title?: string;
  note?: string;
  responsibleId?: number;
  propertyId?: number;
  buildingId?: number;
  personId?: number;
  followUpId?: number | null;
  scheduledAt?: string;
  timezone?: string;
  recurrence?: ReminderRecurrenceConfig;
  metadata?: Record<string, unknown> | null;
  status?: ReminderStatus;
}

export interface ReminderBuildingSummary {
  id: number;
  street: string;
  number: number;
  block?: string | null;
  stair?: string | null;
}

export interface ReminderDTO {
  id: number;
  title: string;
  note: string | null;
  responsibleId: number;
  creatorId: number;
  propertyId: number | null;
  buildingId: number | null;
  personId: number | null;
  followUpId: number | null;
  scheduledAt: Date;
  timezone: string;
  recurrenceType: ReminderRecurrenceType;
  recurrenceRule: string | null;
  recurrenceEndsAt: Date | null;
  status: ReminderStatus;
  metadata: Record<string, unknown> | null;
  createdAt: Date;
  updatedAt: Date;
  recurrenceDescription?: string;
  responsible?: ReminderUserSummary | null;
  creator?: ReminderUserSummary | null;
  property?: ReminderPropertySummary | null;
  building?: ReminderBuildingSummary | null;
  person?: ReminderPersonSummary | null;
  followUp?: ReminderFollowUpSummary | null;
}

export interface ReminderOccurrenceDTO {
  id: number;
  reminderId: number;
  followUpId: number | null;
  scheduledFor: Date;
  originalScheduledFor: Date | null;
  timezone: string;
  status: ReminderOccurrenceStatus;
  completedAt: Date | null;
  skippedAt: Date | null;
  skippedReason: string | null;
  autoGenerated: boolean;
  sequence: number;
  metadata: Record<string, unknown> | null;
  reminder?: ReminderDTO | null;
}

export interface AgendaQueryParams {
  start: string;
  end: string;
  responsibleId?: string;
  includeCompleted?: string;
}

export interface UpdateOccurrenceStatusRequest {
  status: ReminderOccurrenceStatus;
  completedAt?: string;
  skippedAt?: string;
  skippedReason?: string;
  followUpId?: number | null;
  scheduledFor?: string;
  actionNote?: string;
  metadata?: Record<string, unknown> | null;
}

export interface ReminderQueryParams {
  responsibleId?: string;
  status?: string;
  search?: string;
  propertyId?: string;
  buildingId?: string;
  personId?: string;
  followUpId?: string;
  page?: string;
  limit?: string;
  sortBy?: string;
  sortOrder?: "asc" | "desc";
  startDate?: string;
  endDate?: string;
}

export interface ReminderListResponse {
  data: ReminderDTO[];
  pagination: {
    page: number;
    limit: number;
    total: number;
    totalPages: number;
  };
}

export interface AgendaResponse {
  data: ReminderOccurrenceDTO[];
  meta: {
    start: string;
    end: string;
    responsibleId?: number;
  };
}

